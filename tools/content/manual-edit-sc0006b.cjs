// 人工式定点编辑（第二轮）：sc-0006 剩余真实缺陷。
// 逐条对应审核证据，只动必要节点。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① n5 场景矛盾：n2 的选项承诺「敲门」，但 n5 正文写的是小满自己出现在厨房门口
 *（n3 分支也会到达 n5，那里没有敲门动作）→ 选项必须不预设敲门。
 * 修法：改 n2 的第二个选项文字。 */
byId['n2'].choices.forEach(c => {
  if (c.to === 'n5') c.text = '先不出声，自己再翻一遍柜子';
});

/* ② n8「两炉一起端上桌」却只写一盘 → 不数盘子，避免与任一来路冲突 */
byId['n8'].text = '窗外刚泛出一点灰，阿栗被叫起来，坐在桌边，头发还压着一道印。蜡烛插上了，火苗在没开灯的屋里晃。桌上那盘蛋糕切面敞着，旁边搁着刀叉。阿栗伸手去拿，嘴里道了声谢。小陶站在他手边，盯着那盘东西，喉咙里那句话已经排到嘴边，还没出声。蜡油顺着蜡烛往下淌。';

/* ③ blocker：n9 来路是「只端新出炉的（甜）」，n10 却写「咸味先到」→ 事实冲突。
 * 修法：n10 不指定是哪种味，只写入口后的迟疑；两个来路（两炉都端 / 只端新炉）都能成立。 */
byId['n10'].text = '阿栗切下一角，叉起来送进嘴里，嚼得很慢。咽下去之前，她的眉毛动了一下，没出声。小陶站在她手边，眼睛盯着她的嘴，喉咙里那句话已经排到嘴边。小满靠在桌沿，看看阿栗，又看看小陶。蜡烛立在蛋糕中间，蜡油一滴一滴往下淌，窗外那片灰还是灰的。屋里谁都没动。';

/* ④ n11 来路是「低头承认盐当糖放了」，正文却说那半句话卡在喉咙里没出来 → 前后否认。
 * 修法：写成他已经说出口、此刻正在等回应。 */
byId['n11'].text = '阿栗把叉子放回盘边，说她其实早就知道。屋里一下静了。小陶刚说出口的那些话还悬在半空，人站在桌边没动；小满看看阿栗，又看看小陶，手还搭在桌沿上。蜡烛的火苗晃了一下，蜡油淌到盘边的纸上。蛋糕还剩在那里，切面敞着，谁也没再动刀。窗外那片灰比刚才亮了一点，但还没白。';

/* ⑤ n13 结局：来路包含「把咸味说成海盐特调」这条撒谎线，结局却说「话都说出来了」→ 冲突。
 * 修法：结局只写此刻的状态，不断言是否说了实话。 */
byId['n13'].text = '蜡烛烧到一半，蜡油在盘边积了一小滩。阿栗把手里那一角吃完，小陶和小满也各挖了一块，吃着吃着，动作都慢下来。盘子中间还剩大半个，切面敞着，颜色不匀的那圈边没人碰。谁也没再提这蛋糕是怎么来的。窗外那片灰终于泛出白，屋里的灯始终没开。';

/* ⑥ n5 里的贺卡残句（「最后一行空着」）与 n3 分支冲突 → 删掉贺卡细节。 */
byId['n5'].text = '小满不知什么时候站在了厨房门口。小陶把身子挡在蛋糕前，说那是新试的口味，让他回去睡。小满没答话，绕过来，用指甲从切开的角上抠下一块放进嘴\n里。他嚼得很慢，眉头动了一下，然后看向台面上那只写着糖的罐子，又看向小陶。咸味在厨房里散不掉。他把罐子端起来，掂了掂。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('人工编辑已应用：n2 选项、n8 去盘数、n10 去咸味预设、n11 去前后否认、n13 去断言、n5 删贺卡残句');
