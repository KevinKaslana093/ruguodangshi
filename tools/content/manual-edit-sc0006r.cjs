// 结构诊断（这次先做完整推导）：
//   故事简介写的是「补救来不及，坦白又不敢」——**立意就是补救失败**。
//   但 n4/n5 通向 n6 的那条支线写成了「重烤成功（甜的）」，
//   于是 n6/n7 两支的味道不同，而 n8/n9（合并点）与 n10～n14 必须同时容纳两条 →
//   味道漂移无法消除，改多少句都按不住。
//
// 定稿：让 n6/n7 两支**都保持一盘咸蛋糕**，差异只在"怎么端上去"：
//   n6 = 硬着头皮直接端上去，不解释
//   n7 = 切成小块，说这是特制咸味
//   两盘/两炉的说法全部删除；n1 同时交代 小满与阿栗都是同住的室友。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① n1：统一住居设定（小满、阿栗都是同住的室友），并交代糖罐误贴标签 */
byId['n1'].text = '橱柜最上层那个贴着「糖」字的罐子，是上回装盐时贴错了标签，一直没人改；真正的糖袋早见了底。小陶半夜起来烤蛋糕，照标签舀了两勺，直到第一炉出烤箱尝了一口才发现不对。台面上那盘蛋糕切开的角敞着，咸味在厨房里散不掉；旁边压着一张没写完的贺卡，是给阿栗的。走廊两头，阿栗和小满的房门都关着。窗外还是黑的，屋里只亮着一盏小灯。';

/* ② n4 的去向 n6：不再是「重烤」，而是「硬着头皮端上去」 */
byId['n4'].choices.forEach(c => {
  if (c.to === 'n6') c.text = '把蛋糕摆上桌，硬着头皮不解释';
  if (c.to === 'n7') c.text = '切成小块，说这是特制咸味';
});
/* ③ n5 的去向 n6：同样改为不重烤 */
byId['n5'].choices.forEach(c => {
  if (c.to === 'n6') c.text = '把蛋糕摆上桌，硬着头皮不解释';
  if (c.to === 'n7') c.text = '求小满配合，说这是新口味';
});

/* ④ n6：一盘蛋糕，硬着头皮端上去（无第二炉、无"两盘"） */
byId['n6'].text = '小陶把蛋糕端到台面中间，刀、叉、盘子一件件摆开，动作比平时慢。小满靠在橱柜边看着他，没帮忙，也没走开。台面上那盘蛋糕颜色发暗，切开的角敞着，咸味还没散。小陶伸手把贺卡翻过去，字扣在桌面上。窗外的天从黑转成灰。他深吸一口气，说了句：端上去吧。';

/* ⑤ n7：一盘蛋糕，切成小块（与 n6 同层同场，差异只在做法） */
byId['n7'].text = '小陶把那盘蛋糕端到台面中间，拿刀切成一块一块，切面朝上码着，谁想吃哪块自己拿。小满靠在橱柜边看着他，没帮忙，也没走开。写着糖的那只罐子被推到角落，标签还朝外翻着。小陶把贺卡翻过去，字扣在桌面上。窗外的天开始从黑转灰。他说：就当是新口味。';

/* ⑥ n8（n6/n7 合并点）：一盘蛋糕 + 贺卡，不指定做法也不指定味道 */
byId['n8'].text = '窗外刚泛出一点灰，阿栗被叫起来，坐在桌边，头发还压着一道印。蜡烛插上了，火苗在没开灯的屋里晃。蛋糕端到了桌子中间，阿栗伸手去拿刀叉，嘴里道了声谢。小陶站在她手边，盯着桌上那东西，喉咙里那句话已经排到嘴边，还没出声。那张贺卡压在盘子边上，字朝着桌面扣着。蜡油顺着蜡烛往下淌。';

/* ⑦ n9（n6/n7 合并点）：同上，一盘蛋糕 */
byId['n9'].text = '窗外刚泛出一点灰，阿栗坐在桌边，蜡烛点着，火苗把影子压在墙上。蛋糕摆在桌子中间，阿栗的手伸向盘边。小满先开了口，笑着说这盘得先尝一口再评，手艺的事待会儿再说。阿栗的手停在半空，先看小满，又看小陶。小陶站在旁边，嘴张开一半，话还没出来。';

/* ⑧ n11：小陶已坦白；不再断言"人站在桌边没动"与后续动作冲突 */
byId['n11'].text = '阿栗说她其实不怪他。屋里一下静了。小陶刚说出口的那些话还悬在半空；小满看看阿栗，又看看小陶，手还搭在桌沿上。蜡烛的火苗晃了一下，蜡油淌到盘边的纸上。窗外那片灰比刚才亮了一点，但还没白。';

/* ⑨ n13（e2 结局）：容纳"推远盘子"与"闷头吃完"两条来路 —— 只写天光与桌面的静止 */
byId['n13'].text = '蜡烛烧到一半，蜡油在盘边积了一小滩。桌上慢慢安静下来，谁也没再开口。盘子摆在桌子中间，切面朝上。窗外那片灰终于泛出白，屋里的灯始终没开，谁也没去开。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('定稿 v16 已应用：两条支线都保持一盘咸蛋糕（消除味道漂移）、统一住居设定');
