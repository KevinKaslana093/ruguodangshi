// 人工式定点编辑（定稿 v27）。
//
// 加强后的编辑审核（专门盯「选项承诺的动作是否在落点兑现」）报出三条，全部为真实缺陷：
//   ① n8→n10「把咸味说成海盐特调」：落点上小陶始终没开口 → n10 补上他当场圆场的说法。
//      n10 的另一条来路是 n9→n10「顺着小满的圆场编下去」，同样是「编」，因此 n10 写他
//      当场把咸味说成特调，对两条来路都成立。
//   ② n10→n13「把盘子推远，说吃不下就算」：n13 写「谁也没再开口」，与「说出口」冲突，
//      且推盘动作没兑现 → 选项改为「不再解释，随她去」（n13 的沉默场景可兑现）。
//   ③ n5→n7「拉小满一起圆场」：n7 里小满全程只是旁观，没参与 → 选项改为如实描述 n7 的动作
//      （把盘子摆体面 + 说成新口味）。**注意** n7 由 n4、n5 共享，不能要求小满参与
//      —— 这是合并点纪律：同层来路的承诺必须都落在共享落点能兑现的范围内。
// 另：n12 去掉「把那点事说完」（避免断言他说了什么，与 n8→n10 的海盐线冲突）。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

const setChoice = (from, to, text) => {
  const c = (byId[from].choices || []).filter(x => x.to === to)[0];
  if (!c) throw new Error('缺选项 ' + from + '→' + to);
  c.text = text;
};

/* ① n10 兑现「把咸味说成海盐特调」（同时兼容 n9→n10 的「顺着小满的圆场编下去」） */
byId['n10'].text = '阿栗切下一角，叉起来送进嘴里。小陶抢在她开口前接了话，说这是他新试的做法，加了点海盐，咸口是特意留的。阿栗嚼得很慢，咽下去之前，眉毛动了一下，没出声。小陶站在她手边，眼睛盯着她的嘴，话已经说完了，剩下的只能等。小满靠在桌沿，看看阿栗，又看看小陶。蜡烛立在蛋糕中间，蜡油一滴一滴往下淌，窗外那片灰还是灰的。屋里谁都没动。';

/* ② 选项改为 n13 能兑现的写法 */
setChoice('n10', 'n13', '不再解释，随她去');

/* ③ 选项如实描述 n7 的动作（不要求小满参与） */
setChoice('n5', 'n7', '摆得体面些，就说是新口味');

/* n12 去掉对「他说了什么」的断言 */
byId['n12'].text = '阿栗又叉了一块，含在嘴里，慢慢点了点头，说这样也挺好吃，像哪家铺子会做的点心。小满先没忍住，笑出声，伸手也切了一角。小陶从兜里把卡片拿出来，放在阿栗手边。三个人围着那盘蛋糕，一人一角地挖，蜡烛烧到一半，火苗在没开灯的屋里晃。天从灰里透出一点白，盘底慢慢刮出了声音。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('定稿 v27 已应用：n10 兑现海盐说法、n10→n13 选项改写、n5→n7 选项如实、n12 去断言');
