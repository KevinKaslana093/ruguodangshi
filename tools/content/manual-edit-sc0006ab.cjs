// 加强后的编辑审核抓出两条「选项承诺了动作、落点没兑现」（这正是我们要它盯的类别）：
//   ① n1→n3「把咸蛋糕装盒，先写贺卡」→ n3 却写「蛋糕和那只空盒子并排搁着」（盒子还是空的）
//   ② n2→n5「先不出声，把空糖袋收起来」→ n5 完全没提糖袋
//
// 修法：让**两个选择各自兑现**——
//   ① n3：开场就写把蛋糕装进盒子（与 n1→n2 那条路「蛋糕敞着摆在台面上」区分开）。
//      注意 n3 之后 n4/n5 由 n2、n3 两条来路共享，因此 n4/n5 不能指定蛋糕是否在盒里；
//      这里让 n3 只写到「装盒」这个动作发生，n4/n5 用中性写法（后面复核）。
//   ② n5：补上收糖袋的动作。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① n3 兑现「装盒」 */
byId['n3'].text = '小陶把蛋糕装进盒子，扣上盖，又觉得这样送出去太像敷衍，把盖又揭开了。他摊开贺卡，笔帽咬在嘴里，写下「阿栗，生日快乐」，又写了两行平常的话，笔尖停在最后一行上，没往下写。台面另一头，盒子敞着盖，蛋糕里的咸味还在往屋里散。他在想，要不要在贺卡里提一句——不提，阿栗第一口就会尝到；提了，这个生日就从一开始带着道歉。';

/* ② n5 兑现「收糖袋」 */
byId['n5'].text = '隔壁房门响了一下，小满趿着拖鞋站在了厨房门口。小陶手忙脚乱地把那只空糖袋团起来塞进围裙口袋里，又把身子挡在蛋糕前，说那是新试的口味，让他回去睡。小满没答话，走过来，伸手从盘沿掰下一小块放进嘴里。他嚼得很慢，眉毛挑起来，随即看向台面上那只写着糖的罐子。他把罐子端起来，掂了掂，又放回去。窗外还是黑的。';

/* 复核 n4：它由 n2、n3 共享（n2 那条路蛋糕敞着，n3 那条路装过盒）→ 不指定盒与盘的状态 */
byId['n4'].text = '天快亮了，能指望的只有隔壁。小陶敲了两下，小满隔着门应了一声，趿着拖鞋出来了，头发压得乱七八糟。小陶掰下一角推到他面前，说了实话：罐子拿错了，舀进面糊里的是盐。小满捏起蛋糕咬了一口，嚼了两下，没咽下去，也没吐出来，只把杯子往边上挪了挪。他说糖的事他回头翻翻自己抽屉，可这会儿重做来不及。咸味还没散。两个人站在小灯底下，怎么办还没商量出来。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('定稿 v26 已应用：n3 兑现装盒、n5 兑现收糖袋、n4 改为不指定盒/盘状态');
