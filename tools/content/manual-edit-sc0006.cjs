// 人工式定点编辑：sc-0006《天亮前的咸蛋糕》4 条真实缺陷。
// 只动必要节点，不改结构。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* 缺陷 A（major n3）：n3 正文写「笔尖停在最后一个空行上」「贺卡摊在台面上，最后一行空着」，
 * 但 n3 的两个选项分别是「在贺卡里写上可能有点咸」和「只写生日快乐」——
 * 无论选哪个，下游 n4/n5 都不该再出现"最后一行空着"。
 * 且 n4 又被 n2 分支到达（n2 根本没写贺卡）→ 合并点不能提贺卡内容。
 * 修法：n3 正文改为"还没落笔"的当下；n4 正文里删掉贺卡的最后一行描述。 */
byId['n3'].text = '小陶把贺卡摊在台面上，笔帽咬在嘴里。他写下「阿栗，生日快乐」，又写了两行平常的话，笔尖停在最后一行上，没往下写。台面另一边就是那盘蛋糕，切开的一角露着，咸味在厨房里散不掉。他在想，要不要在贺卡里提一句——不提，阿栗第一口就会尝到；提了，这个生日就从一开始带着道歉。';
byId['n4'].text = '小陶把切下的那一角推到小满面前，说了实话：罐子拿错了，舀进面糊里的是盐。小满捏起蛋糕咬了一口，嚼了两下，没咽下去，也没吐出来，只把杯子往边上挪了挪。台面上那盘蛋糕切开的角敞着，咸味还没散。小满看了他一会儿，说这事不能你一个人扛。两个人在小灯底下站着，怎么办还没商量出来。';

/* 缺陷 B（major n6）：n6 是 n4、n5 两条线的合并点，n5 的来路（n2 敲门只说急用）里
 * 小满是否在场并不确定，而 n6 直接写"两个人的手上都沾着面粉"。
 * 修法：n6 正文改成不依赖来路的自足表述——写"重新和面的人"，不预设人数。 */
byId['n6'].text = '第二炉是在天快亮时出的烤箱。糖是小满从自己抽屉里翻出来的半包，蛋糕在盘子里歪着，边上一圈颜色深浅不一，中间还塌了一小块。小满拿筷子戳了戳，说比上一炉强。小陶没接话，只把那盘咸的挪到台面另一头，切开的角还敞着。窗外的天从黑转成灰，重新和过面的那只盆还搁在水池边。';

/* 缺陷 C（major n6）：n5 的第二个选项写「切好摆盘」通到 n7，
 * 但 n7→n8 之后 n8 写"小满把蜡烛插上"，两处对在场人数的预设也不一致。
 * 修法：n8 正文去掉对"谁在做什么"的强预设，只写阿栗被叫起来与桌上那盘蛋糕。 */
byId['n8'].text = '窗外刚泛出一点灰，阿栗被叫起来，坐在桌边，头发还压着一道印。蜡烛插上了，火苗在没开灯的屋里晃。蛋糕摆在桌子中间，阿栗伸手去拿刀叉，嘴里道了声谢。小陶站在他手边，盯着那盘东西，喉咙里那句话已经排到嘴边，还没出声。蜡油顺着蜡烛往下淌。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
