const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① n4：撤回"小满手持糖"（与 n6 的"从抽屉翻出"冲突）。
 *    改为他空手出来，糖的事留给 n6 当场交代。 */
byId['n4'].text = '小满从屋里出来了，趿着拖鞋，头发压得乱七八糟。小陶把切下的那一角推到他面前，说了实话：罐子拿错了，舀进面糊里的是盐。小满捏起蛋糕咬了一口，嚼了两下，没咽下去，也没吐出来，只把杯子往边上挪了挪。台面上那盘蛋糕切开的角敞着，咸味还没散。小满看了他一会儿，说这事不能你一个人扛。两个人在小灯底下站着，怎么办还没商量出来。';

/* ② n6：第二炉也没救回来（同样是咸的）——糖的来源在本节点当场交代，
 *    下游所有节点因此都能成立。 */
byId['n6'].text = '小满回屋翻自己的抽屉，摸出半包没拆完的糖，倒在台面上。第二炉是在天快亮时出的烤箱，蛋糕在盘子里歪着，边上一圈颜色深浅不一，中间还塌了一小块。小满拿筷子戳了一角尝，眉头皱起来——还是咸的。他把筷子放下，说这罐子怕不是从头到尾都装的盐。小陶没接话，把两盘都摆到台面这头，切开的角都敞着。窗外的天从黑转成灰。';

/* ③ n12 结局（e1）：恢复"咸"的说法——此时无论哪条路，桌上都是咸蛋糕。 */
byId['n12'].text = '阿栗又叉了一块，含在嘴里，慢慢点了点头，说咸的也挺好吃，像哪家铺子会做的咸口点心。小满先没忍住，笑出声，伸手也切了一角。小陶的脸烫起来，叉子犹豫着跟过去。三个人围着那盘蛋糕，一人一角地挖，蜡烛烧到一半，火苗在没开灯的屋里晃。天从灰里透出一点白，盘底慢慢刮出了声音。';

/* ④ n13 结局（e2）：同上，可安全指认咸味。 */
byId['n13'].text = '蜡烛烧到一半，蜡油在盘边积了一小滩。阿栗把手里那一角吃完，越吃越慢，最后把叉子放下了。小陶和小满也没再动。那点咸味在嘴里留着，谁都没说破。盘子里还剩下大半个，切面敞着。窗外那片灰终于泛出白，屋里的灯始终没开。';

/* ⑤ 统一「阿栗」的指代（编辑审核指出 n8 用了"他"）。 */
byId['n8'].text = String(byId['n8'].text).replace(/小陶站在他手边/, '小陶站在她手边');
byId['n10'].text = String(byId['n10'].text).replace(/小陶站在他手边/, '小陶站在她手边');

