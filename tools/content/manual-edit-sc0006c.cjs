// 人工式定点编辑（终稿）：sc-0006。
// 关键认识：n6 选项「两炉一起端上桌，把话说开」承诺了"坦白"，
// 但 n8 仍提供「把咸味说成海盐特调」（撒谎）→ 无论怎么改下游都会与选项承诺冲突。
// 真正的病根在 n6 的选项措辞。逐条解决后，下游不再需要断言"是否说了实话"。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① 病根：n6 选项不再承诺「把话说开」→ 与 n8 的撒谎选项不再矛盾 */
byId['n6'].choices.forEach(c => {
  if (c.to === 'n8') c.text = '两炉一起端上桌，先不解释';
});

/* ② n8：不数盘子、不预设几盘（来路有"两炉都端"与"只端新炉"两种） */
byId['n8'].text = '窗外刚泛出一点灰，阿栗被叫起来，坐在桌边，头发还压着一道印。蜡烛插上了，火苗在没开灯的屋里晃。蛋糕摆在桌子中间，阿栗伸手去拿刀叉，嘴里道了声谢。小陶站在他手边，盯着桌上那东西，喉咙里那句话已经排到嘴边，还没出声。蜡油顺着蜡烛往下淌。';

/* ③ n10：不指定入口是什么味道（来路可能是甜的新炉，也可能是咸的旧炉） */
byId['n10'].text = '阿栗切下一角，叉起来送进嘴里，嚼得很慢。咽下去之前，她的眉毛动了一下，没出声。小陶站在她手边，眼睛盯着她的嘴，喉咙里那句话已经排到嘴边。小满靠在桌沿，看看阿栗，又看看小陶。蜡烛立在蛋糕中间，蜡油一滴一滴往下淌，窗外那片灰还是灰的。屋里谁都没动。';

/* ④ n13 结局：不断言"话都说出来了"（来路包含撒谎线）→ 只写此刻的状态 */
byId['n13'].text = '蜡烛烧到一半，蜡油在盘边积了一小滩。阿栗把手里那一角吃完，小陶和小满也各挖了一块，吃着吃着，动作都慢下来。盘子中间还剩大半个，切面敞着，颜色不匀的那圈边没人碰。谁也没再提这蛋糕是怎么来的。窗外那片灰终于泛出白，屋里的灯始终没开。';

/* ⑤ n5：删掉贺卡残句（n3 分支才写贺卡，n2 分支没有） */
byId['n5'].text = '小满不知什么时候站在了厨房门口。小陶把身子挡在蛋糕前，说那是新试的口味，让他回去睡。小满没答话，绕过来，用指甲从切开的角上抠下一块放进嘴里。他嚼得很慢，眉头动了一下，然后看向台面上那只写着糖的罐子，又看向小陶。咸味在厨房里散不掉。他把罐子端起来，掂了掂。';

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('终稿人工编辑已应用（5 处，含病根修正：n6 选项不再承诺坦白）');
