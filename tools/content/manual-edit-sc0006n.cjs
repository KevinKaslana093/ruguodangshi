// 人工式定点编辑（终稿 v12 — 定稿）。
//
// 反复出现的最后根因：**合并点写了过强的状态断言**（"谁也没再动刀""还剩大半个"
// "那点事始终没被说破"），而结局节点必须同时容纳多条来路 → 必然互相打架。
// 定稿原则：合并点只写**动作正在发生**的瞬间，不写"再也没…""谁也没…"这种终局断言；
// 终局断言只允许出现在结局节点自己身上。
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..', '..');
const p = path.join(R, 'content', 'drafts', 'sc-0006.json');
const d = JSON.parse(fs.readFileSync(p, 'utf8'));
const s = d.story;
const byId = {};
s.nodes.forEach(n => { byId[n.id] = n; });

/* ① n11（合并点）：去掉"谁也没再动刀"这种终局断言 */
byId['n11'].text = '阿栗说她其实不怪他。屋里一下静了。小陶刚说出口的那些话还悬在半空，人站在桌边没动；小满看看阿栗，又看看小陶，手还搭在桌沿上。蜡烛的火苗晃了一下，蜡油淌到盘边的纸上。窗外那片灰比刚才亮了一点，但还没白。';

/* ② n13（e2）：去掉与来路冲突的动作断言，只写天光与静止 */
byId['n13'].text = '蜡烛烧到一半，蜡油在盘边积了一小滩。桌上的东西谁也吃不动了，叉子搁回盘边。小陶和小满都没再动。窗外那片灰终于泛出白，屋里的灯始终没开，谁也没去开。';

/* ③ n3：让"装盒"这个上游选项在正文里落实（否则 n1 选装盒的线不成立）。
 *    写法：贺卡与蛋糕都在台面上，盒在一边空着（两种来路都成立）。 */
byId['n3'].text = '小陶把贺卡摊在台面上，笔帽咬在嘴里。他写下「阿栗，生日快乐」，又写了两行平常的话，笔尖停在最后一行上，没往下写。台面另一头，蛋糕和那只还没派上用场的盒子并排搁着。咸味在厨房里散不掉。他在想，要不要在贺卡里提一句——不提，阿栗第一口就会尝到；提了，这个生日就从一开始带着道歉。';

/* ④ n4 的选项再顺一遍：正文已说"说了实话"，选项就不再重复"承认" */
byId['n4'].choices.forEach(c => {
  if (c.to === 'n6') c.text = '拉小满一起重烤一炉';
  if (c.to === 'n7') c.text = '切成小块，说这是特制咸味';
});

['editorReview', 'pathReview', 'fixLog', 'fixRounds', 'regressions', 'mergeCheck', 'finalCheck', 'check'].forEach(k => { delete d[k]; });
fs.writeFileSync(p, JSON.stringify(d, null, 1), 'utf8');
console.log('终稿 v12 已应用：n11/n13 去过强状态断言、n3 落实装盒线、n4 选项去重复');
