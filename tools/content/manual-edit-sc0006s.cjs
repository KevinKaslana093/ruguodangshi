setChoice('n3', 'n5', '只写生日快乐，蛋糕照送');

/* n4：小满知情后的两种态度 */
setChoice('n4', 'n6', '把蛋糕摆上桌，硬着头皮不解释');
setChoice('n4', 'n7', '切成小块，说这是特制咸味');

