const GENRES = Object.keys(CONFLICTS);
const perGenre = parseInt(arg('per-genre', '10'), 10);
const startId = parseInt(arg('start', '9'), 10);
const batch = arg('batch', '2');

let id = startId;
const items = [];
const used = {};
GENRES.forEach(g => {
  const list = CONFLICTS[g].slice(0, perGenre);
  list.forEach(seed => {
    const sid = 'sc-' + String(id).padStart(4, '0');
    id++;
    items.push({ id: sid, genre: g, premium: false, seed });
    used[g] = (used[g] || 0) + 1;
  });
});

const plan = {
  batch: batch,
  note: 'B 档：每题材补足 10 个正式故事（共 80 个）；seed 为各不相同的核心冲突线索；非 premium 档（12–16 节点、路径 6–9 段、3 结局）。',
  counts: used,
  items
};
